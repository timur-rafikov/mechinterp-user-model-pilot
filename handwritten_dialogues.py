def build_turns(base, tail, condition, signal_text):
    if condition == "distractor":
        return base + [signal_text] + tail, None
    if condition == "reveal_early":
        return [signal_text] + base + tail, 0
    if condition == "reveal_mid":
        return base + [signal_text] + tail, 3
    if condition == "reveal_late":
        return base + tail[:1] + [signal_text] + tail[1:], 4
    raise ValueError(condition)


def main():
    out_path = Path(__file__).parent / "data" / "dialogues.jsonl"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    records = []
    dialogue_id = 0
    for t in TOPICS:
        conditions = ["reveal_mid"] + (["reveal_early", "reveal_late"] if t["has_position_variants"] else [])
        for condition in conditions:
            for trait, signal in [("low_competence", t["reveal_low"]), ("high_competence", t["reveal_high"])]:
                turns, reveal_idx = build_turns(t["base"], t["tail"], condition, signal)
                records.append({
                    "dialogue_id": f"d{dialogue_id:04d}",
                    "condition": condition,
                    "trait": trait,
                    "topic": t["topic"],
                    "signal_text": signal,
                    "reveal_turn_index": reveal_idx,
                    "turns": turns,
                })
                dialogue_id += 1

        turns, _ = build_turns(t["base"], t["tail"], "distractor", t["distractor"])
        records.append({
            "dialogue_id": f"d{dialogue_id:04d}",
            "condition": "distractor",
            "trait": "neutral",
            "topic": t["topic"],
            "signal_text": t["distractor"],
            "reveal_turn_index": None,
            "turns": turns,
        })
        dialogue_id += 1

    with out_path.open("w") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"Wrote {len(records)} dialogues to {out_path}")


if __name__ == "__main__":
    main()
