def build_turns(base, tail, condition, signal_text):
    if condition == "distractor":
        return base + [signal_text] + tail, None
    if condition == "reveal_early":
        return [signal_text] + base + tail, 0
    if condition == "reveal_mid":
        return base + [signal_text] + tail, 3
    if condition == "reveal_late":
        return base + tail[:1] + [signal_text] + tail[1:], 4
    raise ValueError(condition)


def main():
    out_path = Path(__file__).parent / "data" / "dialogues.jsonl"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    records = []
    dialogue_id = 0

    def add(condition, trait, topic_str, signal, base, tail):
        nonlocal dialogue_id
        turns, reveal_idx = build_turns(base, tail, condition, signal)
        records.append({
            "dialogue_id": f"d{dialogue_id:04d}",
            "condition": condition,
            "trait": trait,
            "topic": topic_str,
            "signal_text": signal,
            "reveal_turn_index": reveal_idx,
            "turns": turns,
        })
        dialogue_id += 1

    for t in TOPICS:
        for signal in t["reveal_low"]:
            add("reveal_mid", "low_competence", t["topic"], signal, t["base"], t["tail"])
        for signal in t["reveal_high"]:
            add("reveal_mid", "high_competence", t["topic"], signal, t["base"], t["tail"])
        for signal in t["distractor"]:
            add("distractor", "neutral", t["topic"], signal, t["base"], t["tail"])

        if t["has_position_variants"]:
            add("reveal_early", "low_competence", t["topic"], t["reveal_low"][0], t["base"], t["tail"])
            add("reveal_early", "high_competence", t["topic"], t["reveal_high"][0], t["base"], t["tail"])
            add("reveal_late", "low_competence", t["topic"], t["reveal_low"][0], t["base"], t["tail"])
            add("reveal_late", "high_competence", t["topic"], t["reveal_high"][0], t["base"], t["tail"])

    with out_path.open("w") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"Wrote {len(records)} dialogues to {out_path}")


if __name__ == "__main__":
    main()
